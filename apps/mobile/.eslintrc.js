// Was a real gap: package.json defines `npm run lint` and lists
// @react-native/eslint-config as a devDependency, but no config file
// existed anywhere in the repo — running lint either errored immediately
// or silently did nothing, so nothing in this codebase has actually been
// linted despite the tooling being present. `.eslintrc.js` (not the newer
// flat `eslint.config.js`) to match @react-native/eslint-config's own
// expected format and this package.json's lack of `"type": "module"` —
// same ESM/CJS reasoning vitest.config.ts's own comment documents.
module.exports = {
  root: true,
  extends: "@react-native",
  rules: {
    // NativeWind can't reach React Native's `gap` via a Tailwind
    // className (see theme/spacing.ts's own comment on this) — inline
    // `style={{ gap: ... }}` is the deliberate, documented pattern used
    // throughout this codebase, not something worth flagging on every one
    // of its ~100+ call sites.
    "react-native/no-inline-styles": "off",
  },
  ignorePatterns: [
    "node_modules/",
    "web-build/",
    "dist/",
    "coverage/",
    // Generated by `npm run gen:types` from apps/api's OpenAPI spec — not
    // hand-written, not worth linting.
    "src/api/types.gen.ts",
  ],
};
